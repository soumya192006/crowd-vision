import React, { useState, useMemo } from 'react';
import { Download, Trash2, Search, Filter, AlertCircle, ArrowDownRight, ArrowUpRight, Plus, Minus } from 'lucide-react';
import { EventLog } from '../types';
import { exportEventLogsToCSV } from '../utils/csvExport';

interface EventLogsTableProps {
  logs: EventLog[];
  onClearLogs: () => void;
  isRealBackend: boolean;
}

export function EventLogsTable({ logs, onClearLogs, isRealBackend }: EventLogsTableProps) {
  const [filterType, setFilterType] = useState<string>('all');
  const [searchQuery, setSearchQuery] = useState<string>('');

  const filteredLogs = useMemo(() => {
    return logs.filter((log) => {
      // Type match
      if (filterType !== 'all' && log.type !== filterType) {
        return false;
      }
      // Search query
      if (searchQuery.trim()) {
        const query = searchQuery.toLowerCase();
        const descMatch = log.description.toLowerCase().includes(query);
        const idMatch = log.trackId ? String(log.trackId).includes(query) : false;
        const typeMatch = log.type.toLowerCase().includes(query);
        if (!descMatch && !idMatch && !typeMatch) return false;
      }
      return true;
    });
  }, [logs, filterType, searchQuery]);

  const handleExportCSV = () => {
    exportEventLogsToCSV(filteredLogs);
  };

  const getBadgeForType = (type: EventLog['type']) => {
    switch (type) {
      case 'track_created':
        return (
          <span className="inline-flex items-center gap-1 text-emerald-400 font-medium">
            <Plus className="w-3 h-3" />
            <span>Track Created</span>
          </span>
        );
      case 'track_lost':
        return (
          <span className="inline-flex items-center gap-1 text-slate-400 font-medium">
            <Minus className="w-3 h-3" />
            <span>Track Lost</span>
          </span>
        );
      case 'line_crossed_in':
        return (
          <span className="inline-flex items-center gap-1 text-emerald-300 font-semibold">
            <ArrowDownRight className="w-3.5 h-3.5 text-emerald-400" />
            <span>Line Cross [IN]</span>
          </span>
        );
      case 'line_crossed_out':
        return (
          <span className="inline-flex items-center gap-1 text-rose-300 font-semibold">
            <ArrowUpRight className="w-3.5 h-3.5 text-rose-400" />
            <span>Line Cross [OUT]</span>
          </span>
        );
      case 'system_alert':
        return (
          <span className="inline-flex items-center gap-1 text-blue-400 font-medium">
            <AlertCircle className="w-3 h-3" />
            <span>System Alert</span>
          </span>
        );
      default:
        return <span className="text-slate-400">{type}</span>;
    }
  };

  return (
    <div className="bg-slate-900 border border-slate-800 rounded-xl overflow-hidden shadow-sm flex flex-col">
      {/* Top Header & Filter Toolbar */}
      <div className="p-4 bg-slate-900/90 border-b border-slate-800 flex flex-col md:flex-row md:items-center justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <h3 className="text-base font-semibold text-white tracking-tight">Event Audit Logs</h3>
            <span className="text-xs text-slate-400 font-mono">
              ({filteredLogs.length} events)
            </span>
          </div>
          <p className="text-xs text-slate-400 mt-0.5">
            {isRealBackend
              ? 'Real telemetry stream from local Python computer vision backend'
              : 'Simulated tracking lifecycle events generated by demo engine'}
          </p>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2">
          <button
            onClick={handleExportCSV}
            disabled={filteredLogs.length === 0}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-200 hover:text-white bg-slate-800 hover:bg-slate-700/80 border border-slate-700 rounded-lg disabled:opacity-40 transition-colors"
          >
            <Download className="w-3.5 h-3.5 text-blue-400" />
            <span>Export CSV</span>
          </button>

          <button
            onClick={onClearLogs}
            disabled={logs.length === 0}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-rose-300 hover:text-rose-200 bg-rose-950/40 hover:bg-rose-900/40 border border-rose-800/40 rounded-lg disabled:opacity-40 transition-colors"
          >
            <Trash2 className="w-3.5 h-3.5" />
            <span>Clear Logs</span>
          </button>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="px-4 py-2.5 bg-slate-950/70 border-b border-slate-800/80 flex flex-wrap items-center justify-between gap-3 text-xs">
        {/* Search input */}
        <div className="relative flex-1 min-w-[200px] max-w-sm">
          <Search className="w-3.5 h-3.5 absolute left-2.5 top-1/2 -translate-y-1/2 text-slate-500" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="Search by ID, event, or description..."
            className="w-full bg-slate-900 border border-slate-800 rounded-md pl-8 pr-3 py-1.5 text-xs text-slate-200 placeholder-slate-500 focus:outline-none focus:border-blue-500"
          />
        </div>

        {/* Filter tabs */}
        <div className="flex items-center gap-1 p-1 bg-slate-900 rounded-lg border border-slate-800 overflow-x-auto">
          {[
            { id: 'all', label: 'All' },
            { id: 'track_created', label: 'Created' },
            { id: 'line_crossed_in', label: 'Entry [IN]' },
            { id: 'line_crossed_out', label: 'Exit [OUT]' },
            { id: 'track_lost', label: 'Lost' },
            { id: 'system_alert', label: 'System' },
          ].map((tab) => (
            <button
              key={tab.id}
              onClick={() => setFilterType(tab.id)}
              className={`px-2.5 py-1 text-xs font-medium rounded-md whitespace-nowrap transition-colors ${
                filterType === tab.id
                  ? 'bg-blue-600 text-white shadow-sm'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              {tab.label}
            </button>
          ))}
        </div>
      </div>

      {/* High-density Data Table */}
      <div className="overflow-x-auto max-h-[480px]">
        <table className="w-full text-left text-xs border-collapse">
          <thead className="bg-slate-950/80 text-slate-400 font-mono sticky top-0 border-b border-slate-800 z-10">
            <tr>
              <th className="py-2.5 px-4 font-semibold">Timestamp</th>
              <th className="py-2.5 px-4 font-semibold">Frame #</th>
              <th className="py-2.5 px-4 font-semibold">Event Type</th>
              <th className="py-2.5 px-4 font-semibold">Track ID</th>
              <th className="py-2.5 px-4 font-semibold">Confidence</th>
              <th className="py-2.5 px-4 font-semibold">Description</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-800/60 font-sans">
            {filteredLogs.length > 0 ? (
              filteredLogs.map((log) => (
                <tr key={log.id} className="hover:bg-slate-800/40 transition-colors">
                  <td className="py-2.5 px-4 font-mono text-slate-400 whitespace-nowrap tabular-nums">
                    {log.timestamp}
                  </td>
                  <td className="py-2.5 px-4 font-mono text-slate-400 whitespace-nowrap tabular-nums">
                    #{log.frameNumber}
                  </td>
                  <td className="py-2.5 px-4 whitespace-nowrap">
                    {getBadgeForType(log.type)}
                  </td>
                  <td className="py-2.5 px-4 font-mono text-slate-200 whitespace-nowrap">
                    {log.trackId ? (
                      <span className="text-blue-400 font-semibold">#{log.trackId}</span>
                    ) : (
                      <span className="text-slate-600">—</span>
                    )}
                  </td>
                  <td className="py-2.5 px-4 font-mono text-slate-300 whitespace-nowrap tabular-nums">
                    {log.confidence !== undefined ? (
                      `${(log.confidence * 100).toFixed(0)}%`
                    ) : (
                      <span className="text-slate-600">—</span>
                    )}
                  </td>
                  <td className="py-2.5 px-4 text-slate-300 max-w-md truncate">
                    {log.description}
                  </td>
                </tr>
              ))
            ) : (
              <tr>
                <td colSpan={6} className="py-12 text-center text-slate-500">
                  No matching log events found. Adjust filters or resume tracking.
                </td>
              </tr>
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
}
